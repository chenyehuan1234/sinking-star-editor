import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {test} from 'node:test';
import {cameraView} from '../src/core/camera';
import {parseEntities} from '../src/core/entities';
import {levelView} from '../src/core/project';
import {newWorld,validateWorld,WorldCompiler} from '../src/core/world';
import {EditorService} from '../src/main/service';
import {upgradeSpatialWorld} from '../src/world-space';

const root=process.env.SINKING_STAR_GAME??'';
test('自制大地图入口属性、镜头与分屏保存重开后写入原生地图',{skip:!root},async()=>{
 const service=new EditorService(fs.mkdtempSync(path.join(os.tmpdir(),'sstar-custom-world-')));
 const catalog=await service.connect(root);
 const codec=service.codec!,pkg=service.pkg,compiler=new WorldCompiler(pkg,codec);
 const world=upgradeSpatialWorld(newWorld(catalog.sourceHash,catalog.build));
 const original=compiler.file('overworld');
 const source=original.records.find(r=>r.type==='Level_Entry'&&codec.parse(r).complete&&Number(codec.get(r,'style'))===1)!;
 const group=original.records.find(r=>r.type==='Group'&&codec.parse(r).complete)!;
 const groupId=900*0x100000+1,rotation:[number,number,number,number]=[0,0,Math.SQRT1_2,Math.SQRT1_2];
 world.levelGroups=[{id:'puzzles',title:'解谜'}];
 world.levels=[{id:'room',title:'小关',folderId:'puzzles',project:{format:'sinking-star-project',version:3,sourceHash:world.sourceHash,sourceBuild:world.sourceBuild,template:'mirror_1',name:'room',operations:[]}}];
 world.map.entries=[{id:'first',title:'第一入口',levelId:'room',x:7,y:5},{id:'second',title:'第二入口',levelId:'room',x:8,y:5,prototype:{template:'overworld',sourceId:source.id},size:1.25,rotation,scale:[1,2,1],nativeGroupId:groupId,unlocks:['first']}];
 world.map.editor={groups:[{id:'entries',name:'入口组',members:['entry:second']}]};
 world.map.objects=[{kind:'prefab',id:groupId,template:'overworld',sourceId:group.id,position:[7,6,0]}];
 const base=compiler.previewMap(world),main=cameraView(codec,base).controls.find(c=>c.primary&&!c.overview)!;
 assert.ok(main);
 world.map.camera={mode:'single',controls:[{id:main.id,target:[11,8,0],upDistance:26,southDistance:14,fov:49}]};
 const withCamera=compiler.previewMap(world);
 assert.deepEqual(cameraView(codec,withCamera).controls.find(c=>c.id===main.id)?.position,[11,-6,26]);
 world.map.camera=await service.cameraObject(world,{action:'create',kind:'play',role:'aux',sourceId:main.id,position:[11,8,0]});
 const aux=cameraView(codec,compiler.previewMap(world)).controls.find(c=>!c.primary&&!c.overview&&c.name==='extra_view');
 assert.ok(aux);
 world.map.camera={...world.map.camera,mode:'screens',screenSize:[8,9],origin:[2,2],screenCameraId:main.id};
 world.map.spawn=[5,6];
 const saved=path.join(service.workspace,'custom-world.sstar-world.json');
 fs.writeFileSync(saved,JSON.stringify({...world,sourceEvidence:service.evidence(world)}));
 const reopened=JSON.parse(fs.readFileSync(saved,'utf8')) as typeof world;
 assert.match(reopened.sourceEvidence!.schema,/^[a-f0-9]{64}$/);
 validateWorld(reopened);
 const preview=compiler.previewMap(reopened),view=levelView(pkg,'overworld',preview,codec),camera=view.camera!;
 assert.equal(camera.perScreen,true);
 assert.deepEqual(camera.screenSize,[8,9]);
 assert.deepEqual(camera.origin,[2,2]);
 assert.ok(camera.controls.some(c=>c.id===aux.id));
 const built=compiler.build(reopened),map=parseEntities(built.changes.get('data-common/overworld.entities')!);
 const spawn=map.records.find(r=>r.id===view.managedSpawnId)!;
 assert.equal(spawn.type,'Guy');
 assert.equal(codec.get(spawn,'position.x'),5);
 assert.equal(codec.get(spawn,'position.y'),6);
 const spawnView=view.entities.find(entity=>entity.id===view.managedSpawnId)!;
 assert.deepEqual(spawnView.position,[5,6,0]);
 assert.equal(spawnView.cloneable,false);
 const entry=map.records.find(r=>r.id===view.managedEntryIds?.second)!;
 assert.equal(codec.get(entry,'mesh'),codec.get(source,'mesh'));
 assert.equal(codec.get(entry,'style'),1);
 assert.equal(codec.get(entry,'size'),1.25);
 assert.equal(codec.get(entry,'group_id'),groupId);
 assert.equal(codec.get(entry,'scale.y'),2);
 assert.ok(Math.abs(Number(codec.get(entry,'orientation.z'))-rotation[2])<1e-6);
 assert.equal(codec.get(entry,'unlocked_by_id'),view.managedEntryIds?.first);
 assert.deepEqual(cameraView(codec,map).screenSize,[8,9]);
 for(const name of ['overworld','intro'])assert.ok(built.changes.get('data-common/'+name+'.entities'));
 assert.deepEqual(reopened.map.editor?.groups[0].members,['entry:second']);
 assert.equal(reopened.levels[0].folderId,'puzzles');
});
